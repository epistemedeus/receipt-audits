#!/usr/bin/env python3
"""Verify the delivered allowlist/checksums and optional byte-for-byte cold outputs."""
import argparse
import hashlib
from pathlib import Path

HERE=Path(__file__).resolve().parent
OUTPUTS=('PUBLIC-AUDIT.md','derived/summary.json','derived/buys.csv','derived/cold-independent.json')

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--replayed',type=Path,help='directory generated by README commands')
    args=parser.parse_args()
    allowed=(HERE/'FILES.txt').read_text().splitlines()
    if allowed!=sorted(set(allowed)):
        raise ValueError('allowlist must be sorted and unique')
    for name in allowed:
        rel=Path(name)
        if rel.is_absolute() or '..' in rel.parts or not (HERE/rel).is_file():
            raise ValueError('unsafe or missing delivered member: '+name)
    checks={}
    for line in (HERE/'SHA256SUMS').read_text().splitlines():
        digest,name=line.split('  ',1)
        if name in checks:
            raise ValueError('duplicate checksum member')
        checks[name]=digest
    if set(checks)!=set(allowed)-{'SHA256SUMS'}:
        raise ValueError('allowlist/checksum set differs')
    for name,digest in checks.items():
        actual=hashlib.sha256((HERE/name).read_bytes()).hexdigest()
        if actual!=digest:
            raise ValueError('checksum mismatch: '+name)
    print('PASS: all '+str(len(allowed))+' delivered paths and SHA-256 checksums')
    if args.replayed is not None:
        for name in OUTPUTS:
            generated=args.replayed/(name[len('derived/'):] if name.startswith('derived/') else name)
            if generated.read_bytes()!=(HERE/name).read_bytes():
                raise ValueError('cold output bytes differ: '+name)
            print('BYTE_IDENTICAL '+name+' '+checks[name])

if __name__=='__main__':main()
